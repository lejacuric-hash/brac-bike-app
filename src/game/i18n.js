export const LANGUAGES = ['hr', 'en']

// Cached so the same function is returned per language (safe in effect deps)
const tCache = {}
export const getT = (lang) => (tCache[lang] ||= gameI18n.getFixedT(lang))

export const getContent = (lang) => (lang === 'hr' ? hrContent : enContent)

export function detectLanguage() {
  try {
    return navigator.language?.toLowerCase().startsWith('hr') ? 'hr' : 'en'
  } catch {
    return 'en'
  }
}

export function formatDistance(meters) {
  if (meters == null) return '—'
  return meters < 1000 ? `${Math.round(meters)} m` : `${(meters / 1000).toFixed(1)} km`
}

export function formatDuration(totalSeconds) {
  const s = Math.max(0, Math.round(totalSeconds))
  const d = Math.floor(s / 86400)
  const h = Math.floor((s % 86400) / 3600)
  const m = Math.floor((s % 3600) / 60)
  if (d > 0) return `${d} d ${h} h`
  if (h > 0) return `${h} h ${m} min`
  return `${m} min`
}

export function formatDate(iso, lang) {
  try {
    return new Date(iso).toLocaleDateString(lang === 'hr' ? 'hr-HR' : 'en-GB')
  } catch {
    return ''
  }
}
